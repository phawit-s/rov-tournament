"use client";

import { useEffect } from "react";

/**
 * ซ่อนป้ายสำรอง "widget โหลดไม่ขึ้น" เมื่อโค้ดฝั่งเบราว์เซอร์ทำงานแล้ว
 *
 * ป้ายนั้นฝังอยู่ใน HTML ของ layout เพื่อให้รอดกรณีที่โค้ดไม่ทำงานเลย
 * (ไฟล์หายหลัง deploy / ส่วนขยายบล็อก / เบราว์เซอร์เก่า) — ดูเหตุผลเต็มที่นั่น
 *
 * ★ ห้ามลบโหนดนั้นทิ้งด้วย DOM ดิบ ★
 *
 * ของเดิมเรียก element.remove() ซึ่งพังเพราะป้ายนั้น "React เป็นคนเรนเดอร์"
 * (มันอยู่ใน JSX ของ layout) พอโหนดหายไปจากจอโดยที่ React ไม่รู้ React ก็ยัง
 * ถือ fiber ที่ชี้ไปโหนดนั้นในฐานะพี่น้องตัวถัดไปใน container อยู่ —
 * ครั้งต่อไปที่มันต้องแทรกอะไรก่อนหน้าโหนดนั้นจะได้ NotFoundError ทันที:
 *
 *   Failed to execute 'insertBefore' on 'Node':
 *   The node before which the new node is to be inserted is not a child of this node
 *
 * ที่โผล่เฉพาะ widget เพลงเพราะมันเป็นตัวเดียวที่ return null ตอนคิวว่าง
 * แล้วกลับมาเรนเดอร์ใหม่ตอนมีเพลงเข้า — ซึ่งคือจังหวะที่ React ต้องแทรกโหนดพอดี
 *
 * วิธีที่ถูกคือแตะของที่อยู่ "นอกต้นไม้ของ React" แทน: ติดธงไว้ที่ <html>
 * แล้วให้ CSS เป็นคนซ่อน — ได้ผลเหมือนกันทุกประการ และยังรอดกรณีโค้ดไม่ทำงาน
 * เพราะถ้าโค้ดไม่รัน ธงก็ไม่ถูกติด ป้ายก็โผล่ตามกำหนดเดิม
 */
export default function BootFallback() {
  useEffect(() => {
    /*
      ตั้งใจไม่คืนค่าตอน unmount — ทิศทางที่ปลอดภัยคือ "ซ่อนค้างไว้"
      ถ้าถอดธงตอน unmount ป้ายจะเด้งกลับมาบนสตรีมตอน React รื้อต้นไม้
      (เช่นตอน HMR ระหว่าง dev) ทั้งที่ทุกอย่างทำงานปกติ
    */
    document.documentElement.dataset.widgetBooted = "1";
  }, []);

  return null;
}
